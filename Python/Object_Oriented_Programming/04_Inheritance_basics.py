# What is Inheritance?
# =========================================

# Inheritance allows one class
# to acquire the properties and
# behaviors of another class.

# In simple words:
# A child class can reuse code
# from a parent class.

# Benefits:
# - Code Reusability
# - Cleaner Programs
# - Easier Maintenance
# - Better Organization
